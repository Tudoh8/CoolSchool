        /// <summary>A cart garage item (paint, add-on, trail or horn) from CartGarageData: its reveal prefab is made by the race builder.</summary>
        static Seed Garage(string id)
        {
            CartGarageData.Item data = CartGarageData.Find(id);
            return new Seed(id, RewardKind.Cart, data.PrefabName, data.CartPose ? CartReveal : Vector3.zero, data.Starter);
        }

        /// <summary>
        /// Sets the cart part (and the paint colour or horn cue) of a Cart item: the garage tables say what the garage items are, the
        /// old extras keep their ids (flag and stickers are add-ons, gold is a paint), and any other Cart seed is a body.
        /// </summary>
        static void ApplyCartInfo(RewardItem item)
        {
            if (item.kind != RewardKind.Cart)
            {
                item.cartPart = CartPart.None;
                return;
            }

            CartGarageData.Item data = CartGarageData.Find(item.id);
            if (data.Id != null)
            {
                item.cartPart = data.Part;
                item.paintColor = data.Colour;
                item.soundCue = data.SoundCue ?? "";
                return;
            }

            switch (item.id)
            {
                case "cart.flag":
                case "cart.stickers":
                    item.cartPart = CartPart.Addon;
                    break;
                case "cart.gold":
                    item.cartPart = CartPart.Paint;
                    item.paintColor = new Color(1f, 0.78f, 0.2f);
                    break;
                default:
                    item.cartPart = CartPart.Body;
                    break;
            }
        }

