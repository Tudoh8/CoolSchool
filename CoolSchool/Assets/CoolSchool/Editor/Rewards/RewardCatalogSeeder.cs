using System.Collections.Generic;
using System.Linq;
using CoolSchool.Rewards;
using UnityEditor;
using UnityEngine;

namespace CoolSchool.EditorTools
{
    /// <summary>
    /// Creates or updates Assets/CoolSchool/Rewards/Catalog.asset with the presents in the order they are given.
    /// Models are found by name. Items already in the catalog keep their reveal tweaks; their model and kind are refreshed.
    /// </summary>
    public static class RewardCatalogSeeder
    {
        const string RewardsFolder = "Assets/CoolSchool/Rewards";
        const string CatalogPath = RewardsFolder + "/Catalog.asset";

        /// <summary>One wanted item. PrefabName is the exact model name; null means "find any pirate hat".</summary>
        readonly struct Seed
        {
            public readonly string Id;
            public readonly RewardKind Kind;
            public readonly string PrefabName;
            public readonly Vector3 RevealEuler;   // only used when the item is new; hand tweaks in the asset are kept
            public readonly bool Starter;          // owned from the start, never given in a present
            public readonly string GoldOf;         // for a gold variant: the id of the item it copies

            public Seed(string id, RewardKind kind, string prefabName)
            {
                Id = id;
                Kind = kind;
                PrefabName = prefabName;
                RevealEuler = Vector3.zero;
                Starter = false;
                GoldOf = "";
            }

            public Seed(string id, RewardKind kind, string prefabName, Vector3 revealEuler, bool starter = false, string goldOf = "")
            {
                Id = id;
                Kind = kind;
                PrefabName = prefabName;
                RevealEuler = revealEuler;
                Starter = starter;
                GoldOf = goldOf;
            }
        }

        // Soapbox carts lie flat (about 1.7 m long): tipped a little toward the camera so the seat shows while they spin.
        // RevealStage does not stand a Cart up like a sword; the model is fitted to the stage by its longest side.
        static readonly Vector3 CartReveal = new Vector3(15f, 0f, 0f);
        const string RaceFolder = "Assets/CoolSchool/Race/Prefabs/";

        // Order: the three starters, the 17 presents, then the 11 gold variants (same model as the item they copy).
        static readonly Seed[] Seeds =
        {
            new Seed("sword.foam", RewardKind.Sword, "SM_Wep_Sword_Foam_01", Vector3.zero, starter: true),
            new Seed("shield.basic", RewardKind.Shield, "SM_Wep_Shield_01", Vector3.zero, starter: true),
            new Seed("cart.racer_1", RewardKind.Cart, "SM_Veh_Soapbox_Racer_01", CartReveal, starter: true),
            new Seed("sword.plastic", RewardKind.Sword, "SM_Wep_Sword_Plastic_01"),
            new Seed("hat.knight_helmet", RewardKind.Hat, "SM_Chr_Attach_Cardboard_KnightHelmet_01"),
            new Seed("plush.dino", RewardKind.PlushToy, "SM_Prop_Plush_Dino_01"),
            new Seed("cart.flag", RewardKind.Cart, "SM_Prop_Flag_01"),
            new Seed("sword.wood", RewardKind.Sword, "SM_Wep_Sword_Wood_02"),
            new Seed("shield.round", RewardKind.Shield, "SM_Wep_Shield_03"),
            new Seed("cart.racer_2", RewardKind.Cart, "SM_Veh_Soapbox_Racer_02", CartReveal),
            new Seed("plush.parrot", RewardKind.PlushToy, "SM_Prop_Toy_Parrot_01"),
            new Seed("plush.unicorn", RewardKind.PlushToy, "SM_Prop_Plush_Unicorn_01"),
            new Seed("hat.cap", RewardKind.Hat, "SM_Chr_Attach_Hat_Cap_Back_01"),
            new Seed("cart.stickers", RewardKind.Cart, "CS_Cart_Stickers", CartReveal),   // generated by the race builder
            new Seed("sword.pirate", RewardKind.Sword, "SM_Wep_Sword_Plastic_02"),
            new Seed("sword.foam_big", RewardKind.Sword, "SM_Wep_Sword_Foam_03"),
            new Seed("plush.bear", RewardKind.PlushToy, "SM_Prop_Plush_Bear_01"),
            new Seed("cart.racer_3", RewardKind.Cart, "SM_Veh_Soapbox_Racer_03", CartReveal),
            new Seed("hat.pirate", RewardKind.Hat, "SM_Chr_Attach_Hat_Pirate_01"),
            new Seed("cart.gold", RewardKind.Cart, "CS_Cart_Gold", CartReveal),   // generated by the race builder

            Gold("gold.sword.wood", "sword.wood"),
            Gold("gold.plush.dino", "plush.dino"),
            Gold("gold.hat.knight_helmet", "hat.knight_helmet"),
            Gold("gold.shield.round", "shield.round"),
            Gold("gold.plush.unicorn", "plush.unicorn"),
            Gold("gold.sword.pirate", "sword.pirate"),
            Gold("gold.hat.cap", "hat.cap"),
            Gold("gold.plush.bear", "plush.bear"),
            Gold("gold.sword.plastic", "sword.plastic"),
            Gold("gold.hat.pirate", "hat.pirate"),
            Gold("gold.sword.foam_big", "sword.foam_big"),
        };

        /// <summary>A gold copy of a present. Kind, model and reveal pose are copied from the base seed when the catalog is built.</summary>
        static Seed Gold(string id, string baseId)
        {
            return new Seed(id, RewardKind.Sword, null, Vector3.zero, false, baseId);
        }

        [MenuItem("CoolSchool/Rewards/Seed Catalog")]
        static void SeedFromMenu()
        {
            RewardCatalog catalog = CreateOrUpdate();
            Selection.activeObject = catalog;
        }

        /// <summary>Makes or refreshes the catalog asset and returns it.</summary>
        public static RewardCatalog CreateOrUpdate()
        {
            PlaygroundPrototypeBuilder.EnsureFolder("Assets/CoolSchool", "Rewards");

            var catalog = AssetDatabase.LoadAssetAtPath<RewardCatalog>(CatalogPath);
            if (catalog == null)
            {
                catalog = ScriptableObject.CreateInstance<RewardCatalog>();
                AssetDatabase.CreateAsset(catalog, CatalogPath);
            }

            catalog.items = BuildItems(catalog.items);
            RewardIconRenderer.AssignIcons(catalog);
            EditorUtility.SetDirty(catalog);
            AssetDatabase.SaveAssets();
            return catalog;
        }

        static List<RewardItem> BuildItems(List<RewardItem> existing)
        {
            var result = new List<RewardItem>();
            foreach (Seed listed in Seeds)
            {
                // A gold variant uses the kind, model and reveal pose of the item it copies.
                Seed seed = listed;
                if (!string.IsNullOrEmpty(listed.GoldOf))
                {
                    Seed baseSeed = Seeds.FirstOrDefault(s => s.Id == listed.GoldOf);
                    if (baseSeed.Id == null)
                    {
                        Debug.LogWarning($"CoolSchool: gold reward '{listed.Id}' copies unknown item '{listed.GoldOf}', skipping it.");
                        continue;
                    }
                    seed = new Seed(listed.Id, baseSeed.Kind, baseSeed.PrefabName, baseSeed.RevealEuler, false, listed.GoldOf);
                }

                GameObject prefab = seed.PrefabName != null ? FindPrefab(seed.PrefabName) : FindPirateHat();
                if (prefab == null)
                {
                    Debug.LogWarning($"CoolSchool: no model found for reward '{seed.Id}' ({seed.PrefabName}), skipping it."
                        + (seed.PrefabName != null && seed.PrefabName.StartsWith("CS_Cart_") ? " The race builder makes it; run it before the reward seeder." : string.Empty));
                    continue;
                }

                RewardItem item = existing != null ? existing.Find(e => e != null && e.id == seed.Id) : null;
                if (item == null) item = new RewardItem { id = seed.Id, revealScale = 1f, revealEuler = seed.RevealEuler };

                item.kind = seed.Kind;
                item.prefab = prefab;
                item.starter = seed.Starter;
                item.goldOf = seed.GoldOf ?? "";
                result.Add(item);
            }

            // Anything added by hand stays, after the seeded items.
            if (existing != null)
                result.AddRange(existing.Where(e => e != null && !Seeds.Any(s => s.Id == e.id)));
            return result;
        }

        static GameObject FindPrefab(string prefabName)
        {
            // Prefabs generated by the race builder: load by path first (they may not be in the search index yet).
            if (prefabName.StartsWith("CS_Cart_"))
            {
                var generated = AssetDatabase.LoadAssetAtPath<GameObject>(RaceFolder + prefabName + ".prefab");
                if (generated != null) return generated;
            }

            foreach (string guid in AssetDatabase.FindAssets(prefabName + " t:Prefab"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (System.IO.Path.GetFileNameWithoutExtension(path) != prefabName) continue;

                var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                if (prefab != null) return prefab;
            }
            return null;
        }

        /// <summary>Any prefab whose name contains both "Pirate" and "Hat".</summary>
        static GameObject FindPirateHat()
        {
            string bestPath = null;
            foreach (string guid in AssetDatabase.FindAssets("Pirate Hat t:Prefab"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                string fileName = System.IO.Path.GetFileNameWithoutExtension(path);
                if (!fileName.Contains("Pirate") || !fileName.Contains("Hat")) continue;

                if (bestPath == null || string.CompareOrdinal(fileName, System.IO.Path.GetFileNameWithoutExtension(bestPath)) < 0)
                    bestPath = path;
            }
            return bestPath != null ? AssetDatabase.LoadAssetAtPath<GameObject>(bestPath) : null;
        }
    }
}
